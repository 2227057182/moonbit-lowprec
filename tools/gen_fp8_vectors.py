"""Generates `fp8_vectors.mbt`: every 8-bit pattern of E4M3 and E5M2 with its
exact value.

The decoding here is written from the format definitions with `Fraction`
arithmetic only, so it shares no code with the MoonBit implementation it
checks. Values are exact because an 8-bit float is a dyadic rational with a
small exponent; the decimal strings below are therefore lossless.

    python3 tools/gen_fp8_vectors.py > fp8_vectors.mbt
"""

import math
import sys
from decimal import Decimal
from fractions import Fraction


def dec(v):
    """Exact decimal text for a float, always with a fractional part."""
    s = format(Decimal(v), "f")
    if "." not in s:
        s += ".0"
    return s


def e4m3(byte):
    sign = -1 if byte & 0x80 else 1
    e = (byte >> 3) & 0xF
    m = byte & 0x7
    if (byte & 0x7F) == 0x7F:
        return None, 1  # NaN: 0x7F and 0xFF only
    if e == 0:
        v = Fraction(m, 512)
    else:
        v = Fraction(8 + m, 8) * Fraction(2) ** (e - 7)
    return sign * float(v), 0


def e5m2(byte):
    sign = -1 if byte & 0x80 else 1
    e = (byte >> 2) & 0x1F
    m = byte & 0x3
    if e == 31:
        return None, 1 if m else 2
    if e == 0:
        v = Fraction(m, 65536)
    else:
        v = Fraction(4 + m, 4) * Fraction(2) ** (e - 15)
    return sign * float(v), 0


HEADER = '''/// Reference table generated by `tools/gen_fp8_vectors.py`, which decodes
/// both formats with exact rational arithmetic. `special` is 0 for finite,
/// 1 for NaN and 2 for infinity.
pub struct Fp8Row {
  bits : Int
  value : Double
  special : Int
}

pub let e4m3_rows : Array[Fp8Row] = [
'''

FOOTER = ']\n\npub let e5m2_rows : Array[Fp8Row] = [\n'


def rows(fn):
    out = []
    for b in range(256):
        value, special = fn(b)
        v = "0.0" if value is None else dec(value)
        out.append(f"  {{ bits: {b}, value: {v}, special: {special} }},")
    return "\n".join(out)


def main():
    text = HEADER + rows(e4m3) + FOOTER + rows(e5m2) + "]\n\n"
    text += (
        "// Spot checks against the published format definitions: E4M3 has\n"
        "// no infinity, its largest finite value is 448 at 0x7E, the smallest\n"
        "// positive value is 2^-9 at 0x01, and only 0x7F/0xFF are NaN. E5M2\n"
        "// has infinities at 0x7C/0xFC and its largest finite value is 57344.\n"
        "// python3: e4m3[0x7e]=448.0, e5m2[0x7b]=57344.0\n"
    )
    sys.stdout.write(text)
    print(
        f"rows: e4m3 max {e4m3(0x7E)[0]}, e5m2 max {e5m2(0x7B)[0]}, "
        f"e4m3 min {e4m3(0x01)[0]}, e5m2 min {e5m2(0x01)[0]}, "
        f"e5m2 inf {e5m2(0x7C)[1]}, nan count "
        f"{sum(1 for b in range(256) if e4m3(b)[1] == 1)}/"
        f"{sum(1 for b in range(256) if e5m2(b)[1] == 1)}",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
